// examples/tinyllm/src/text_font.h — a 5x7 bitmap font covering the FULL printable ASCII range
// (32..126), including lowercase.
//
// Why not tools/common/debug_font.h: that atlas is uppercase, digits and `:!.-` only, which is
// fine for a HUD but cannot render what a language model emits — lowercase prose with commas,
// apostrophes and quotes. So tinyllm ships its own glyph set, baked into its own bundle exactly
// the way miracle-player bakes its heart and spark textures.
//
// The atlas is 128x96 RGBA: 16 columns x 12 rows of 8x8 cells = 192 glyphs, laid out as the 96
// printable characters TWICE — cells 0..95 in white (generated text) and 96..191 in amber
// (the status line). Two colours with no tinting, because the GBA PPU cannot tint a BG tile;
// the console picks a colour by picking a tile index. Three colours total (transparent, white,
// amber) also means the tier-0 bake encodes it as 4bpp paletted tiles without complaint.
