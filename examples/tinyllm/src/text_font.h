// Tilemap CELL VALUE for a character in the given colour bank.
//
// The +1 is the engine's tilemap convention, not an accident: a cell value of 0 means "empty" and
// a value v selects tileset tile v-1 (identical in the software backend and the GBA PPU —
// soft_renderer.cpp `int t = cell - 1` / gba_ppu.cpp `e.tile = ts.base + c - 1`). Dropping it
// renders every character as the one before it in the atlas, which is exactly the bug this
// comment exists to prevent; tests/unit/test_tinyllm_font.cpp pins the mapping against the atlas.
//
// Anything outside 32..127 becomes the hollow box, so a stray byte from the model is visible
// rather than silently blank.
inline uint16_t font_cell(char ch, bool amber = false) {
    int c = int(static_cast<unsigned char>(ch)) - 32;
    if (c < 0 || c >= kFontGlyphs) c = kFontGlyphs - 1;
    return uint16_t(c + (amber ? kFontBankB : 0) + 1);
}

// The inverse, for tests and for reading a console back as text.
inline char font_char(uint16_t cell) {
    if (cell == 0) return ' ';
    int c = int(cell) - 1;
    if (c >= kFontBankB) c -= kFontBankB;
    return char(c + 32);
}

