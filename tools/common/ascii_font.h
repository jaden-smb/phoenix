// tools/common/ascii_font.h — a 5x7 bitmap font covering the FULL printable ASCII range
// (32..126, lowercase included), rendered into a 128x48 RGBA atlas of 8x8 cells (16 cols x 6
// rows; cell 0 == ASCII 32, so the engine's BitmapFont defaults — first_char=32, cols=16 —
// sample it directly). Host-only, like debug_font.h (which stays: it is uppercase-only and the
// existing tools/bakes depend on its exact atlas). The glyph table is the same one tinyllm's
// console bakes (examples/tinyllm/src/text_font.h); it is copied, not included, because tools
// must not depend on an example. Glyphs sit at a 1px top/left pad inside their cell, so a
// BitmapFont with advance = 6 gives a dense 6px text pitch.
