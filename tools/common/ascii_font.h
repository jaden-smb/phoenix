// Fills `atlas` (kAsciiFontW * kAsciiFontH RGBA8 texels) with white glyphs on transparent.
inline void build_ascii_font(uint32_t* atlas) {
    for (int i = 0; i < kAsciiFontW * kAsciiFontH; ++i) atlas[i] = 0u;
    for (int g = 0; g < kAsciiGlyphs; ++g) {
        const int cx = (g % 16) * 8, cy = (g / 16) * 8;
        for (int ry = 0; ry < 7; ++ry)
            for (int rx = 0; rx < 5; ++rx)
                if (kAscii5x7[g][ry] & (0x10 >> rx))
                    atlas[(cy + ry + 1) * kAsciiFontW + (cx + rx + 1)] = 0xFFFFFFFFu;
    }
}

