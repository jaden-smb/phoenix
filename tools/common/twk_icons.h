// Render the atlas (kIconAtlasW x kIconAtlasH, phx RGBA = R|G<<8|B<<16|A<<24) into `out`.
inline void build_icon_atlas(uint32_t* out) {
    for (int i = 0; i < kIconAtlasW * kIconAtlasH; ++i) out[i] = 0;
    for (int ic = 0; ic < kIconCount; ++ic) {
        const char* const* rows = icon_rows(ic);
        const int ox = (ic % kIconCols) * kIconSize, oy = (ic / kIconCols) * kIconSize;
        for (int y = 0; y < kIconSize; ++y)
            for (int x = 0; x < kIconSize; ++x) {
                const char c = rows[y][x];
                const uint32_t a = c == '#' ? 255u : c == '+' ? 110u : 0u;
                if (a) out[(oy + y) * kIconAtlasW + ox + x] = 0x00FFFFFFu | (a << 24);
            }
    }
}

